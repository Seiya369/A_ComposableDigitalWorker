/** Native integration smoke; run with Harness listening on WORKFORCE_URL. */
import { chromium, expect } from '@playwright/test';
import { mkdir, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { authenticateWeb } from '../../integration/web-auth.mjs';
const base = process.env.WORKFORCE_URL || 'http://127.0.0.1:3080';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1450, height: 1050 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('dialog', async dialog => dialog.accept());
const api = async (action, payload, options) => { const r=await page.request.post(`${base}/digital-workers/api/command`,{data:{action,payload,options},headers:{Origin:base}}); if(!r.ok())throw new Error(await r.text());return r.json();};
const snapshot = async () => (await page.request.get(`${base}/digital-workers/api/state`)).json();
const prefix='QA-UI-'+Date.now();
const saveEmployeeConfiguration=async()=>{
  const response=page.waitForResponse(response=>response.url().endsWith('/digital-workers/api/command') && response.request().postDataJSON()?.action==='employee.configuration.save');
  await page.getByRole('button',{name:'保存配置',exact:true}).click();
  expect((await response).ok()).toBe(true);
  await expect(page.getByRole('status')).toHaveText('员工配置已保存');
  await expect(page.getByRole('button',{name:'保存配置',exact:true})).toBeDisabled();
};
await mkdir('artifacts/ui',{recursive:true});
try {
  const auth = await authenticateWeb(await readFile(resolve(process.env.WORKFORCE_SERVICE_LOG || '.local/service/stdout.log'), 'utf8'), base);
  const split = auth.cookie.indexOf('=');
  await page.context().addCookies([{ name: auth.cookie.slice(0, split), value: auth.cookie.slice(split+1), url: base, httpOnly: true, sameSite: 'Strict' }]);
  await page.goto(base,{waitUntil:'domcontentloaded'});
  console.log('Native loaded');
  await page.getByRole('button',{name:'数字员工模板',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('tab',{name:'组织架构',exact:true})).toHaveAttribute('aria-selected','true');
  const softwareTeam=page.getByRole('button',{name:'软件开发团',exact:true});
  await expect(softwareTeam).toHaveAttribute('aria-expanded','true');
  await softwareTeam.click();
  await expect(softwareTeam).toHaveAttribute('aria-expanded','false');
  await expect(page.getByRole('button',{name:'配置团队成员 技术负责人（架构师），第 1 级',exact:true})).toBeHidden();
  await softwareTeam.click();
  await expect(softwareTeam).toHaveAttribute('aria-expanded','true');
  await expect(page.getByRole('button',{name:'配置团队成员 技术负责人（架构师），第 1 级',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'配置团队成员 技术负责人（架构师）',exact:true}).click();
  await expect(page.getByRole('tab')).toHaveCount(6);
  await expect(page.getByLabel('所属团队',{exact:true})).toContainText('软件开发团');
  await expect(page.getByRole('combobox',{name:'所属层级',exact:true})).toHaveValue('1');
  await expect(page.getByLabel('所属上级',{exact:true})).toBeDisabled();
  await page.screenshot({path:'artifacts/ui/template-architect.png'});
  for(const label of ['岗位定义','能力组合','模型选择','知识与记忆','权限','交付标准']) {
    await page.getByRole('tab',{name:label,exact:true}).click();
    await expect(page.getByRole('tabpanel',{name:label,exact:true})).toBeVisible();
  }
  await page.getByRole('tab',{name:'能力组合',exact:true}).click();
  await page.screenshot({path:'artifacts/ui/architect-capabilities.png'});
  console.log('Six module tabs verified');
  await page.getByRole('button',{name:'添加员工',exact:true}).first().click();
  await page.getByLabel('员工名称',{exact:true}).fill(prefix);
  await page.getByLabel('所属团队',{exact:true}).selectOption('');
  await page.getByLabel('岗位角色',{exact:true}).fill('验证配置的保存与项目隔离。');
  await page.getByLabel('工作职责',{exact:true}).fill('检查当前项目配置。');
  await page.getByRole('tab',{name:'能力组合',exact:true}).click();
  await page.getByRole('button',{name:'添加技能',exact:true}).click();
  await page.getByLabel('技能 ID',{exact:true}).fill('architecture-review');
  await page.getByLabel('显示名称',{exact:true}).fill('架构审查');
  await page.getByLabel('使用说明',{exact:true}).fill('审查模块边界');
  await page.getByRole('tab',{name:'知识与记忆',exact:true}).click();
  await page.getByRole('region',{name:'投喂马料',exact:true}).getByRole('button',{name:'为投喂马料添加知识来源',exact:true}).click();
  await page.getByLabel('标题',{exact:true}).fill('测试知识');
  await page.getByLabel('知识内容',{exact:true}).fill('仅为界面集成验证使用。');
  await page.getByRole('tab',{name:'交付标准',exact:true}).click();
  await page.getByRole('button',{name:'添加交付物',exact:true}).click();
  await page.getByRole('textbox',{name:'必需交付物 1',exact:true}).fill('配置审查报告');
  await page.getByRole('button',{name:'添加验收标准',exact:true}).click();
  await page.getByRole('textbox',{name:'验收标准 1',exact:true}).fill('七模块配置完整保存');
  await saveEmployeeConfiguration();
  console.log('Template saved');
  const saved=(await snapshot()).templates.find(t=>t.name===prefix);
  if(!saved || saved.modules.capabilities.skills[0]?.name!=='架构审查' || saved.status!=='ready')throw new Error('Saved template did not persist seven module edits');
  await page.getByRole('button',{name:'新建空白团队模板',exact:true}).click();
  await page.getByLabel('团队名称',{exact:true}).fill(prefix+'-团');
  await page.getByLabel('团队简介',{exact:true}).fill('验证独立岗位的统一配置与三层汇报关系');
  await expect(page.locator('.wf-team-toolbar').getByRole('button',{name:'添加员工',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'保存团队',exact:true}).click();
  await expect(page.getByRole('status')).toHaveText('团队模板已保存');
  const team=(await snapshot()).teams.find(t=>t.name===prefix+'-团');
  if(!team)throw new Error('New team was not persisted');
  const teamHeading=page.getByRole('button',{name:team.name,exact:true});
  const leadName=prefix+'-领队';
  const collaboratorName=prefix+'-协作者';
  const workerName=prefix+'-执行员';
  const openTeam=async()=>{
    await teamHeading.click();
    await expect(page.getByRole('tab',{name:'组织架构',exact:true})).toHaveAttribute('aria-selected','true');
  };
  const createTeamEmployee=async(name,manager,level)=>{
    await page.locator('.wf-team-toolbar').getByRole('button',{name:'添加员工',exact:true}).click();
    await expect(page.getByRole('tab')).toHaveCount(6);
    await page.getByLabel('员工名称',{exact:true}).fill(name);
    await expect(page.getByLabel('所属团队',{exact:true})).toHaveValue(team.id);
    const levelSelect=page.getByRole('combobox',{name:'所属层级',exact:true});
    const managerSelect=page.getByLabel('所属上级',{exact:true});
    await levelSelect.selectOption(String(level));
    await expect(levelSelect).toHaveValue(String(level));
    await expect(levelSelect.locator('option:checked')).toHaveText(`第 ${level} 级`);
    if(manager){
      await expect(managerSelect).toBeEnabled();
      await expect(managerSelect).toHaveValue('');
      await expect(page.getByRole('button',{name:'保存配置',exact:true})).toBeDisabled();
      await expect(managerSelect.getByRole('option',{name:manager,exact:true})).toHaveCount(1);
      if(level===3)await expect(managerSelect.getByRole('option',{name:leadName,exact:true})).toHaveCount(0);
      await managerSelect.selectOption({label:manager});
    }else{
      await expect(managerSelect).toBeDisabled();
      await expect(managerSelect).toHaveValue('');
    }
    await saveEmployeeConfiguration();
    await openTeam();
    await expect(page.getByRole('button',{name:`配置团队成员 ${name}`,exact:true})).toContainText(`第 ${level} 级`);
  };
  await createTeamEmployee(leadName,undefined,1);
  await createTeamEmployee(collaboratorName,leadName,2);
  await createTeamEmployee(workerName,collaboratorName,3);
  await page.screenshot({path:'artifacts/ui/team-organization.png'});
  // Choosing the middle employee's level updates its manager options and moves its subtree after saving.
  await page.getByRole('button',{name:`配置团队成员 ${collaboratorName}`,exact:true}).click();
  await expect(page.getByRole('tab')).toHaveCount(6);
  await page.getByLabel('所属层级',{exact:true}).selectOption('1');
  await expect(page.getByLabel('所属层级',{exact:true})).toHaveValue('1');
  await expect(page.getByLabel('所属上级',{exact:true})).toBeDisabled();
  await expect(page.getByLabel('所属上级',{exact:true})).toHaveValue('');
  await saveEmployeeConfiguration();
  await openTeam();
  await expect(page.getByRole('button',{name:`配置团队成员 ${collaboratorName}`,exact:true})).toContainText('第 1 级');
  await expect(page.getByRole('button',{name:`配置团队成员 ${workerName}`,exact:true})).toContainText('第 2 级');
  await page.getByRole('button',{name:`配置团队成员 ${collaboratorName}`,exact:true}).click();
  await page.getByLabel('所属层级',{exact:true}).selectOption('2');
  await expect(page.getByLabel('所属上级',{exact:true})).toHaveValue('');
  await expect(page.getByRole('button',{name:'保存配置',exact:true})).toBeDisabled();
  await expect(page.getByLabel('所属上级',{exact:true}).getByRole('option',{name:collaboratorName,exact:true})).toHaveCount(0);
  await expect(page.getByLabel('所属上级',{exact:true}).getByRole('option',{name:workerName,exact:true})).toHaveCount(0);
  await page.getByLabel('所属上级',{exact:true}).selectOption({label:leadName});
  await saveEmployeeConfiguration();
  await openTeam();
  await expect(page.getByRole('button',{name:`配置团队成员 ${workerName}`,exact:true})).toContainText('第 3 级');
  const organizationState=await snapshot();
  const savedTeam=organizationState.teams.find(t=>t.id===team.id);
  const memberFor=name=>savedTeam?.members.find(member=>organizationState.templates.find(template=>template.id===member.templateId)?.name===name);
  const lead=memberFor(leadName);
  const collaborator=memberFor(collaboratorName);
  const worker=memberFor(workerName);
  if(!savedTeam || savedTeam.members.length!==3 || new Set(savedTeam.members.map(member=>member.memberId)).size!==3 || new Set(savedTeam.members.map(member=>member.templateId)).size!==3 || !lead || lead.reportsTo || !collaborator || collaborator.reportsTo!==lead.memberId || !worker || worker.reportsTo!==collaborator.memberId)throw new Error('Independent employee configurations or three-level reporting hierarchy were not persisted');
  if(await teamHeading.getAttribute('aria-expanded')!=='true')await teamHeading.click();
  await teamHeading.click();
  await expect(teamHeading).toHaveAttribute('aria-expanded','false');
  await expect(page.getByRole('button',{name:`配置团队成员 ${workerName}，第 3 级`,exact:true})).toBeHidden();
  await expect(page.getByRole('button',{name:`配置团队成员 ${workerName}`,exact:true})).toBeVisible();
  await teamHeading.click();
  await expect(teamHeading).toHaveAttribute('aria-expanded','true');
  await page.getByRole('button',{name:`配置团队成员 ${workerName}，第 3 级`,exact:true}).click();
  await expect(page.getByRole('tab')).toHaveCount(6);
  await expect(page.getByLabel('员工名称',{exact:true})).toHaveValue(workerName);
  await expect(page.getByLabel('所属层级',{exact:true})).toHaveValue('3');
  await expect(page.getByLabel('所属上级',{exact:true})).toHaveValue(collaborator.memberId);
  await openTeam();
  await page.getByRole('button',{name:'团队设置',exact:true}).click();
  await page.getByRole('button',{name:'删除团队',exact:true}).click();
  await expect(page.getByRole('status')).toHaveText('团队模板已删除');
  console.log('Unified employee configuration and team hierarchy verified');
  await page.getByRole('button',{name:'关闭数字员工',exact:true}).click();
  if(errors.length)throw new Error('Browser errors: '+errors.join('\n'));
  console.log('PASS: native modal, six module tabs, template save, team hierarchy.');
} catch (error) { console.error(error); await page.screenshot({path:'artifacts/ui/test-failure.png'}); throw error; } finally {
  const state=await snapshot();
  for(const t of state.teams.filter(t=>t.name.startsWith(prefix)))await api('team.delete',{id:t.id});
  for(const m of state.memories.filter(m=>m.title.startsWith(prefix)))await api('memory.delete',{id:m.id});
  for(const e of state.employees.filter(e=>e.name.startsWith(prefix)))await api('employee.delete',{id:e.id});
  for(const t of state.templates.filter(t=>t.name.startsWith(prefix)&&t.status!=='archived'))await api('template.archive',{id:t.id});
  await browser.close();
}
