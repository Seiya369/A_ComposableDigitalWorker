import { normalizeKnowledgeCategory, type KnowledgeSourceCategory } from './library-api.js';
import type { KnowledgeInput } from './types.js';

/** Business provenance controls routing; source wording never proves a preference or a fact. */
export function knowledgeCategoryForInput(input: KnowledgeInput): KnowledgeSourceCategory {
  const category = normalizeKnowledgeCategory(input.category);
  if (input.id.startsWith('memory:') && (input.category === undefined || category === 'reference')) {
    try {
      const provenance = JSON.parse(input.provenance);
      if (provenance?.kind === 'confirmed-memory' && `memory:${provenance.id}` === input.id) {
        if (provenance.source?.kind === 'project-file') return 'reference';
        if (provenance.source?.kind === 'accepted-artifact' || provenance.source?.kind === 'user-confirmed') return 'task-evidence';
      }
    } catch { /* Other provenances are ordinary opaque source metadata. */ }
  }
  if (input.category !== undefined) return category;
  if (input.id === 'team-description' && input.provenance.startsWith('team:')) return 'environment/constraint';
  const kind = /^(run|work-task|work-result|accepted-run|task-goal):/.exec(input.id)?.[1];
  if (!kind || !input.provenance.startsWith(`${kind}:`)) return category;
  if (kind === 'run' || kind === 'work-task') {
    try {
      const record = JSON.parse(input.content);
      if (['failed', 'cancelled', 'blocked'].includes(record?.status)) return 'incident/reflection-proposal';
    } catch { /* A malformed task record is still task evidence, never a model-inferred incident. */ }
  }
  return 'task-evidence';
}

